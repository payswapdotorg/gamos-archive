const packageDirName = "zcode";

export function installScriptSource(baseUrl) {
  return `#!/usr/bin/env sh
set -eu

BASE_URL="\${ZCODE_DIST_BASE_URL:-${baseUrl}}"
INSTALL_DIR="\${ZCODE_DIST_HOME:-$HOME/.zcode/runtime}"
BIN_DIR="\${ZCODE_DIST_BIN_DIR:-$HOME/.local/bin}"

need_cmd() {
  if ! command -v "$1" >/dev/null 2>&1; then
    echo "zcode install requires $1" >&2
    exit 1
  fi
}

need_cmd node
need_cmd curl
need_cmd tar

LATEST_JSON="$(curl -fsSL "\${BASE_URL%/}/latest.json")"
VERSION="$(printf '%s' "$LATEST_JSON" | node -e "let data='';process.stdin.on('data',c=>data+=c);process.stdin.on('end',()=>process.stdout.write(JSON.parse(data).version))")"
TARBALL="$(printf '%s' "$LATEST_JSON" | node -e "let data='';process.stdin.on('data',c=>data+=c);process.stdin.on('end',()=>process.stdout.write(JSON.parse(data).tarball))")"

TMP_DIR="$(mktemp -d)"
cleanup() {
  rm -rf "$TMP_DIR"
}
trap cleanup EXIT

ARCHIVE="$TMP_DIR/$TARBALL"
# 首选上游嵌套布局 releases/<version>/；扁平产物托管（如 GitHub Releases 附件）时回退根路径。
if ! curl -fL "\${BASE_URL%/}/releases/$VERSION/$TARBALL" -o "$ARCHIVE"; then
  curl -fL "\${BASE_URL%/}/$TARBALL" -o "$ARCHIVE"
fi

mkdir -p "$INSTALL_DIR/releases" "$BIN_DIR"
TARGET="$INSTALL_DIR/releases/$VERSION"
rm -rf "$TARGET.new"
mkdir -p "$TARGET.new"
tar -xzf "$ARCHIVE" -C "$TARGET.new"
rm -rf "$TARGET"
mv "$TARGET.new/${packageDirName}" "$TARGET"
rm -rf "$TARGET.new"
ln -sfn "$TARGET" "$INSTALL_DIR/current"

cat > "$BIN_DIR/zcode" <<SH
#!/usr/bin/env sh
exec node "$INSTALL_DIR/current/bin/zcode.mjs" "\\$@"
SH
chmod +x "$BIN_DIR/zcode"
# Gamos 别名：与 zcode 指向同一运行时的第二命令入口。
cp "$BIN_DIR/zcode" "$BIN_DIR/gamos"

echo "ZCode $VERSION installed."
echo "Run: zcode (TUI) or zcode --web (Web)"
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) echo "Note: $BIN_DIR is not in PATH." ;;
esac
`;
}

export function installPowerShellSource(baseUrl) {
  return `# ZCode CLI installer for Windows. Generated by scripts/build-zcode.mjs.
# Mirrors install.sh: reads latest.json from the distribution base URL,
# downloads the runtime tarball (nested releases/<version>/ layout with a
# flat-asset fallback for GitHub Releases), verifies sha256, installs under
# ZCODE_DIST_HOME, and creates zcode/gamos command shims in ZCODE_DIST_BIN_DIR.
# Compatible with Windows PowerShell 5.1 and PowerShell 7+; can be piped:
#   irm <base>/install.ps1 | iex
$ErrorActionPreference = "Stop"

try { [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12 } catch {}

$BaseUrl = "${baseUrl}"
if ($env:ZCODE_DIST_BASE_URL) { $BaseUrl = $env:ZCODE_DIST_BASE_URL }
$InstallDir = Join-Path $HOME ".zcode\\runtime"
if ($env:ZCODE_DIST_HOME) { $InstallDir = $env:ZCODE_DIST_HOME }
$BinDir = Join-Path $HOME ".zcode\\bin"
if ($env:ZCODE_DIST_BIN_DIR) { $BinDir = $env:ZCODE_DIST_BIN_DIR }

function Require-Command([string] $Name) {
  if (-not (Get-Command $Name -ErrorAction SilentlyContinue)) {
    throw ("zcode install requires " + $Name + " on PATH")
  }
}

Require-Command node
Require-Command tar

function Invoke-Download([string] $Url, [string] $OutFile) {
  if (Get-Command curl.exe -ErrorAction SilentlyContinue) {
    & curl.exe -fsSL $Url -o $OutFile
    if ($LASTEXITCODE -ne 0) {
      throw ("download failed: " + $Url)
    }
  } else {
    Invoke-WebRequest -Uri $Url -OutFile $OutFile -UseBasicParsing
  }
}

$BaseUrl = $BaseUrl.TrimEnd("/")
$TmpDir = Join-Path ([System.IO.Path]::GetTempPath()) ("zcode-install-" + [System.Guid]::NewGuid().ToString("N"))
$LatestJson = Join-Path $TmpDir "latest.json"

try {
  New-Item -ItemType Directory -Path $TmpDir -Force | Out-Null
  Invoke-Download ($BaseUrl + "/latest.json") $LatestJson
  $Latest = Get-Content $LatestJson -Raw | ConvertFrom-Json
  $Version = [string] $Latest.version
  $Tarball = [string] $Latest.tarball
  if (-not $Version -or -not $Tarball) {
    throw "latest.json is missing version or tarball"
  }

  $Archive = Join-Path $TmpDir $Tarball
  try {
    Invoke-Download ($BaseUrl + "/releases/" + $Version + "/" + $Tarball) $Archive
  } catch {
    # Flat asset layout (e.g. GitHub Releases attachments): retry from the base root.
    Invoke-Download ($BaseUrl + "/" + $Tarball) $Archive
  }

  if ($Latest.sha256) {
    $Expected = ([string] $Latest.sha256).ToLowerInvariant()
    $Actual = (Get-FileHash -Algorithm SHA256 -Path $Archive).Hash.ToLowerInvariant()
    if ($Actual -ne $Expected) {
      throw ("sha256 mismatch for " + $Tarball)
    }
  }

  $Target = Join-Path $InstallDir ("releases\\" + $Version)
  New-Item -ItemType Directory -Path (Split-Path $Target -Parent) -Force | Out-Null
  $Staging = $Target + ".new"
  if (Test-Path $Staging) { Remove-Item $Staging -Force -Recurse }
  New-Item -ItemType Directory -Path $Staging -Force | Out-Null
  & tar -xzf $Archive -C $Staging
  if ($LASTEXITCODE -ne 0) {
    throw ("tar extract failed for " + $Tarball)
  }
  if (Test-Path $Target) { Remove-Item $Target -Force -Recurse }
  Move-Item (Join-Path $Staging "${packageDirName}") $Target
  Remove-Item $Staging -Force -Recurse

  $Current = Join-Path $InstallDir "current"
  $RunnerBase = $Target
  $CurrentItem = Get-Item $Current -Force -ErrorAction SilentlyContinue
  if ($CurrentItem) {
    if ($CurrentItem.Attributes -band [System.IO.FileAttributes]::ReparsePoint) {
      & cmd.exe /c rmdir "$Current"
    } else {
      Remove-Item $Current -Force -Recurse
    }
  }
  try {
    New-Item -ItemType Junction -Path $Current -Target $Target | Out-Null
    $RunnerBase = $Current
  } catch {
    # Junction unavailable: shims point at the versioned directory instead.
  }

  New-Item -ItemType Directory -Path $BinDir -Force | Out-Null
  $Runner = Join-Path $RunnerBase "bin\\zcode.mjs"
  $CrLf = [string] [char] 13 + [string] [char] 10
  $CmdShim = '@echo off' + $CrLf + 'node "' + $Runner + '" %*' + $CrLf + 'exit /b %ERRORLEVEL%'
  $PsShim = '& node "' + $Runner + '" @args' + $CrLf + 'exit $LASTEXITCODE'
  foreach ($Name in @("zcode", "gamos")) {
    Set-Content -Path (Join-Path $BinDir ($Name + ".cmd")) -Value $CmdShim -Encoding Ascii
    Set-Content -Path (Join-Path $BinDir ($Name + ".ps1")) -Value $PsShim -Encoding Ascii
  }

  Write-Host ("ZCode " + $Version + " installed.")
  Write-Host "Run: zcode (TUI) or zcode --web (Web)"

  $UserPath = [string] [Environment]::GetEnvironmentVariable("Path", "User")
  $PaddedPath = ";" + $UserPath.TrimEnd(";") + ";"
  if ($PaddedPath.IndexOf(";" + $BinDir + ";", [System.StringComparison]::OrdinalIgnoreCase) -lt 0) {
    [Environment]::SetEnvironmentVariable("Path", ($UserPath.TrimEnd(";") + ";" + $BinDir), "User")
    Write-Host ("Note: added " + $BinDir + " to the user PATH. Open a new terminal to use zcode.")
  }
} finally {
  if (Test-Path $TmpDir) { Remove-Item $TmpDir -Force -Recurse -ErrorAction SilentlyContinue }
}
`;
}
